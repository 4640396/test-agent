import { describe, expect, it } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { assertGeneratedFileWritable, generatedFileCoversCases, generationReadBudget, groupCasesForGeneration, summarizeMavenCompilationErrors } from "../src/core/runner.js";
import type { TestCase } from "../src/core/types.js";

function testCase(id: string, target: string): TestCase {
  return { id, target, title: id, scenario: "scenario", steps: [], expected: "expected", priority: "high", layer: "unit" };
}

describe("test generation groups", () => {
  it("uses a bounded dynamic read budget instead of the old fixed six reads", () => {
    expect(generationReadBudget(1)).toBe(12);
    expect(generationReadBudget(4)).toBe(16);
    expect(generationReadBudget(100)).toBe(24);
  });
  it("summarizes Maven compiler locations without exposing the full build output", () => {
    const raw = [
      "[ERROR] D:\\repo\\src\\test\\FooTest.java:[12,9] cannot find symbol",
      "[ERROR] D:\\repo\\src\\test\\BarTest.java:[8,3] cannot find symbol",
      "[INFO] BUILD FAILURE",
    ].join("\n");
    expect(summarizeMavenCompilationErrors(raw)).toBe("D:/repo/src/test/FooTest.java:[12,9] cannot find symbol；D:/repo/src/test/BarTest.java:[8,3] cannot find symbol");
  });
  it("groups cases by production source and assigns one isolated generated test file", () => {
    const groups = groupCasesForGeneration("D:/repo", [
      testCase("aaaaaaaaaaaaaaaa", "src/main/java/demo/Foo.java:10"),
      testCase("bbbbbbbbbbbbbbbb", "src/main/java/demo/Foo.java:20"),
      testCase("cccccccccccccccc", "src/main/java/demo/Bar.java:7"),
    ]);

    expect(groups).toHaveLength(2);
    expect(groups.find((group) => group.sourcePath.endsWith("Foo.java"))).toMatchObject({
      outputPath: "src/test/java/demo/FooAgentGeneratedTest.java",
      cases: [{ id: "aaaaaaaaaaaaaaaa" }, { id: "bbbbbbbbbbbbbbbb" }],
    });
    expect(new Set(groups.map((group) => group.outputPath)).size).toBe(groups.length);
  });

  it("rejects cases without a concrete production source target", () => {
    expect(() => groupCasesForGeneration("D:/repo", [testCase("aaaaaaaaaaaaaaaa", "Foo#doWork")]))
      .toThrow(/缺少可生成测试的目标源码路径/);
  });

  it("protects tracked and non-agent-owned test files from overwrite", () => {
    const root = mkdtempSync(join(tmpdir(), "test-agent-generation-"));
    execFileSync("git", ["init"], { cwd: root, stdio: "ignore" });
    const relative = "src/test/java/demo/FooAgentGeneratedTest.java";
    const absolute = join(root, relative);
    mkdirSync(join(root, "src/test/java/demo"), { recursive: true });
    writeFileSync(absolute, "class UserOwnedTest {}", "utf8");
    expect(() => assertGeneratedFileWritable(root, relative)).toThrow(/非 Test Agent 所有/);

    writeFileSync(absolute, "// Generated by CIMDEV Test Agent\nclass GeneratedTest {}", "utf8");
    execFileSync("git", ["add", relative], { cwd: root, stdio: "ignore" });
    expect(() => assertGeneratedFileWritable(root, relative)).toThrow(/Git 已跟踪/);
  });

  it("reuses an interrupted-run file only when every planned case id is present", () => {
    const root = mkdtempSync(join(tmpdir(), "test-agent-generation-resume-"));
    const [group] = groupCasesForGeneration(root, [
      testCase("case-a", "src/main/java/demo/Foo.java:10"),
      testCase("case-b", "src/main/java/demo/Foo.java:20"),
    ]);
    const absolute = join(root, group.outputPath);
    mkdirSync(join(root, "src/test/java/demo"), { recursive: true });
    writeFileSync(absolute, "// Generated by CIMDEV Test Agent\n@DisplayName(\"[CASE:case-a] A\") class GeneratedTest {}", "utf8");
    expect(generatedFileCoversCases(root, group)).toBe(false);
    writeFileSync(absolute, "// Generated by CIMDEV Test Agent\n// [CASE:case-a]\n// [CASE:case-b]\nclass GeneratedTest {}", "utf8");
    expect(generatedFileCoversCases(root, group)).toBe(true);
  });
});
